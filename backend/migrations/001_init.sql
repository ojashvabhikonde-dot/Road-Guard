-- Initial schema for ROADGUARD AI Module 1
-- Run with psql or any migration runner

CREATE EXTENSION IF NOT EXISTS postgis;

-- Cameras
CREATE TABLE IF NOT EXISTS cameras (
    camera_id UUID PRIMARY KEY,
    name TEXT NOT NULL,
    highway_name TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    direction_deg DOUBLE PRECISION NOT NULL,
    status TEXT NOT NULL DEFAULT 'OFFLINE',
    calibration JSONB,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Detections (one row per detected object per frame)
CREATE TABLE IF NOT EXISTS detections (
    detection_id UUID PRIMARY KEY,
    camera_id UUID REFERENCES cameras(camera_id),
    frame_timestamp TIMESTAMPTZ NOT NULL,
    class TEXT NOT NULL,
    confidence DOUBLE PRECISION NOT NULL,
    bbox GEOMETRY(POLYGON, 4326) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Traffic Queues (aggregated info from detection module)
CREATE TABLE IF NOT EXISTS traffic_queues (
    queue_id UUID PRIMARY KEY,
    camera_id UUID REFERENCES cameras(camera_id),
    location GEOGRAPHY(POINT, 4326) NOT NULL,
    vehicle_count INT NOT NULL,
    queue_length_m DOUBLE PRECISION,
    state TEXT NOT NULL, -- NORMAL, SLOW, CONGESTED, BLOCKED
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Traffic Events (high‑level events generated by Module 1)
CREATE TABLE IF NOT EXISTS traffic_events (
    event_id UUID PRIMARY KEY,
    camera_id UUID REFERENCES cameras(camera_id),
    event_type TEXT NOT NULL,
    confidence DOUBLE PRECISION,
    metadata JSONB,
    timestamp TIMESTAMPTZ NOT NULL,
    location GEOGRAPHY(POINT, 4326),
    created_at TIMESTAMPTZ DEFAULT now()
);

